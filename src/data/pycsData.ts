export function generatePycsConfigFile(channel: string): string {
  const ch = channel.startsWith('#') ? channel : `#${channel}`;
  const chSlug = ch.replace('#', '');
  return `[pycs]
# PYCS Configuration for ${ch}
# Generated for DrFun1 Media Dual UnrealIRCd Hubs & Anope Services
# Upstream Repos: https://github.com/obskyr/pycs.git
channel = ${ch}
network = DrFun1 Media IRC Network
title = ${ch} Channel Statistics - DrFun1 Media
output = /var/www/stats.drfun1ircd.com/pycs/${chSlug}/
format = unrealircd

[hubs]
hub1 = irc.drfun1.com:6697 (SID 001)
hub2 = irc.drfun1media.com:6697 (SID 002)
services = services.drfun1.com / services.drfun1media.com (Anope 2.1)
leaf_count = 1000 (500 on irc.drfun1.com, 500 on irc.drfun1media.com)

[parser]
log_path = /var/log/unrealircd/channels/${ch}.log
encoding = utf-8
ignore_nicks = ChanServ, NickServ, BotServ, OperServ, MemoServ
track_words = true
track_emojis = true
track_quotes = true
min_word_length = 3

[cron]
schedule = */15 * * * *
command = python3 -m pycs --config /etc/pycs/${chSlug}.conf
`;
}
